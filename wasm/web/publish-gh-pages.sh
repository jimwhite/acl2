#!/bin/sh
# Stage the browser harness into a directory that can be published as a static
# site.  Everything is copied flat: the site root is the branch root, so the
# pages, worker.js, lib/ and files/ are siblings.  GitHub Pages can only serve
# a site root of / or /docs on the selected branch, which is why the harness
# gets its own branch (`gh-pages-wasm`, site root /) rather than a subdirectory
# of the documentation branch -- a repository has only one Pages site.
#
#   ./wasm/web/publish-gh-pages.sh /path/to/orphan-branch-worktree
#
# Prerequisites, all of which the build already produces:
#
#   /opt/eclwasm/dist/web-dylink/{ecl.js,ecl.wasm}   WEB=1 DYLINK=1 build
#   wasm/web/files.json, wasm/web/files/            from make-manifest.sh
#   wasm/web/files/dylink-test.fas                  built by aot-book.sh
#
# The dynamic-linking build is used for every page, so only one copy of the
# module is shipped.

set -eu

HERE=$(cd "$(dirname "$0")" && pwd)
ROOT=$(cd "$HERE/../.." && pwd)
DEST=${1:-}
if [ -z "$DEST" ]; then
  echo "usage: $0 <destination directory>" >&2
  exit 2
fi

if [ ! -f "$HERE/files.json" ]; then
  echo "publish: no $HERE/files.json; run wasm/web/make-manifest.sh first" >&2
  exit 1
fi

mkdir -p "$DEST/lib" "$DEST/files"

# Pages.  index-gh.html becomes the site root.
cp "$HERE/index-gh.html" "$DEST/index.html"
cp "$HERE/smoke.html" "$DEST/smoke.html"
cp "$HERE/dylink.html" "$DEST/dylink.html"
cp "$HERE/repl.html" "$DEST/repl.html"
cp "$HERE/acl2.html" "$DEST/acl2.html"
# ACL2 itself, from the serialized world image.  This is the one that works: it
# needs only a page's worth of stack (see WASM-PORT-NOTES.md, "ACL2 runs in a
# page").  It runs on the main thread, not in a worker, so it does not use
# worker.js.
cp "$HERE/acl2-main.html" "$DEST/acl2-main.html"

# The script the ACL2 page feeds to the boot strap.  It lives next to the pages,
# so it has to be published next to them or the page 404s.
cp "$HERE/demo.lsp" "$DEST/demo.lsp"

# What can be include-book'ed, generated by make-manifest.sh from the same list
# that built the payload.
cp "$HERE/books.html" "$DEST/books.html"

# One worker, pointed at the dynamic-linking build for every mode, so the site
# does not have to carry two copies of the ECL module.
sed -e "s|lib/ecl-1536\.js|lib/ecl-dylink.js|g" \
    -e "s|lib/ecl-1536\.|lib/ecl-dylink.|g" \
    "$HERE/worker.js" > "$DEST/worker.js"

cp /opt/eclwasm/dist/web-dylink/ecl.js "$DEST/lib/ecl-dylink.js"
cp /opt/eclwasm/dist/web-dylink/ecl.wasm "$DEST/lib/ecl-dylink.wasm"

# The preloaded ACL2 tree (already gzipped, see make-manifest.sh) and its list.
# make-manifest.sh writes SRC paths that are absolute, because it generates the
# manifest for serving the repository root (where the pages live under
# wasm/web/ and the payload under wasm/web/files/).  The site serves the payload
# from files/, next to the pages, so rewrite the paths on the way out.
python3 - "$HERE/files.json" "$DEST/files.json" <<'PY'
import json, os, sys
entries = json.load(open(sys.argv[1]))
for e in entries:
    e['src'] = 'files/' + os.path.basename(e['src'])
json.dump(entries, open(sys.argv[2], 'w'), indent=2)
PY
cp "$HERE/files"/*.gz "$DEST/files/"

# The module the dynamic-linking page loads, if it is present.
if [ -f "$HERE/files/dylink-test.fas" ]; then
  cp "$HERE/files/dylink-test.fas" "$DEST/files/dylink-test.fas"
fi

# GitHub Pages runs Jekyll unless told not to; it is not wanted here.
: > "$DEST/.nojekyll"

echo "staged $(find "$DEST" -type f | wc -l) files, $(du -sh "$DEST" | cut -f1) in $DEST"
