#!/usr/bin/env python3
"""Regenerate wasm3/module.lisp by re-decoding wasm/milawa-verified.wasm.

W3T::GRAM/BMODULE is a :program-mode function in the generated 3.0 books, so the
bytes -> module step cannot be a theorem; it is this script instead.  The script
is the trusted bridge: it runs the certified decoder (harness/decode.lsp) and
writes what came out.  Re-running it is how the artifact and the proofs are kept
in agreement, and `--check` is what a build should use so a drifted artifact
fails loudly instead of silently invalidating the theorems.

    ./wasm/build.sh                 # assemble the .wat
    ./harness/gen_module.py         # rewrite wasm3/module.lisp
    ./harness/gen_module.py --check # fail if it would change
"""
import pathlib
import re
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
ACL2 = pathlib.Path('/workspaces/acl2/saved_acl2')
SCRIPT = ROOT / 'harness' / 'decode.lsp'
TARGET = ROOT / 'wasm3' / 'module.lisp'

HEADER = """; The decoded module, as a logic constant.
;
; This file is GENERATED by ../harness/gen_module.py, which runs the pinned
; wasm-acl2 binary decoder (../harness/decode.lsp) over
; ../wasm/milawa-verified.wasm and prints what the certified decoder produced.
;
; WHY GENERATED RATHER THAN PROVED.  W3T::GRAM/BMODULE is in :program mode -- the
; decoder is executable but not a logic function -- so "the bytes decode to this"
; cannot be a theorem.  It is therefore a script: gen_module.py re-decodes the
; artifact and rewrites this file, and `--check` fails if the result differs from
; what is checked in.  The gap this leaves is one line of trusted execution of the
; certified decoder, and it is closed by re-running the script, not by argument.
; See wasm3/decode.lisp for what IS proved about the constant.
;
; Everything below the constant is quoteworthy: the module is a ground term, so
; W3T::STEP, W3T::MODULE-P and the field accessors can all be reasoned about.

(in-package "ACL2")

(defconst *milawa-verified-module*
  '{module})
"""


def decode():
    out = subprocess.run([str(ACL2)], stdin=SCRIPT.open('rb'),
                         stdout=subprocess.PIPE, stderr=subprocess.STDOUT,
                         timeout=900, check=False).stdout.decode('utf-8', 'replace')
    if 'PARSE-FAILED' in out:
        sys.exit('decode: the certified decoder rejected wasm/milawa-verified.wasm')
    rest = re.search(r'PARSE-REST=(-?\d+)', out)
    if not rest:
        sys.exit('decode: no PARSE-REST marker; see the decoder output')
    if rest.group(1) != '0':
        sys.exit(f'decode: {rest.group(1)} bytes left over; the parse is not complete')
    m = re.search(r'MODULE-BEGIN=(.*?)=MODULE-END', out, re.S)
    if not m:
        sys.exit('decode: no module printed')
    return m.group(1).strip()


def main():
    module = decode()
    text = HEADER.replace('{module}', module)
    if '--check' in sys.argv[1:]:
        current = TARGET.read_text() if TARGET.exists() else ''
        if current != text:
            sys.exit(f'{TARGET} does not match the artifact; run gen_module.py')
        print(f'{TARGET.name}: up to date')
        return
    TARGET.write_text(text)
    print(f'wrote {TARGET} ({len(module.splitlines())} lines of module)')


if __name__ == '__main__':
    main()
