#!/usr/bin/env python3
"""The example corpus: programs run against the artifact, the model, and the logic.

An example is a file in ../examples/ with two machine-readable lines:

    words: 1 1  1 2  4  5 10  1 10  0  1 20  0
    expect: halted result=10 steps=6 pc=10

WORDS is the program as MVM instruction words.  EXPECT is RECORDED from the
artifact, never written by hand:

    python3 harness/examples.py --record     # run each example in Node, rewrite expect:

and then machine/examples.lisp, generated by

    python3 harness/examples.py --gen-lisp

is an ACL2 book that PROVES the model agrees with the recorded expectation.  So
each example file is the meeting point of two different claims about the same
program:

  * the artifact really does this -- a TEST, in Node, against the .wasm; and
  * the model really does this -- a PROOF, in ACL2, by evaluation.

The third claim, that the artifact and the model agree for all inputs, is L1 and
is not proved yet; that is why the two are recorded separately here rather than
one being derived from the other.

    python3 harness/examples.py --check      # the build: artifact vs expectations

--check is what a build should run.  It fails if the artifact and the recorded
expectations have drifted apart, which is the same discipline as
`../harness/gen_module.py --check` for the pinned store.
"""

import re
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
PROJECT = HERE.parent
EXAMPLES = PROJECT / "examples"
MODULE = PROJECT / "wasm" / "milawa-verified.wasm"
RUN_JS = HERE / "run.js"
LISP_OUT = PROJECT / "machine" / "examples.lisp"

EXPECT_RE = re.compile(r"^expect:\s*(.*)$", re.MULTILINE)
WORDS_RE = re.compile(r"^words:\s*(.*)$", re.MULTILINE)
RESULT_RE = re.compile(
    r"=> (halted|aborted|still \w+) after (\d+) steps(?: with (-?\d+))? \(pc=(-?\d+)\)"
)


def parse(path):
    text = path.read_text()
    words = [int(w) for w in WORDS_RE.search(text).group(1).split()]
    m = EXPECT_RE.search(text)
    return text, words, (m.group(1).strip() if m else "")


def run_artifact(words):
    """Run the real .wasm through the untrusted host and parse what it says."""
    out = subprocess.run(
        ["node", str(RUN_JS), str(MODULE)] + [str(w) for w in words],
        capture_output=True,
        text=True,
    )
    m = RESULT_RE.search(out.stdout)
    if not m:
        raise SystemExit(f"could not read the harness output:\n{out.stdout}\n{out.stderr}")
    status, steps, result, pc = m.groups()
    if status == "halted":
        return f"halted result={result} steps={steps} pc={pc}"
    return f"{status} steps={steps} pc={pc}"


def record(names):
    for path in names:
        text, words, _ = parse(path)
        expect = run_artifact(words)
        new = EXPECT_RE.sub(f"expect: {expect}", text, count=1)
        path.write_text(new)
        print(f"{path.name}: {expect}")


def check(names):
    bad = 0
    for path in names:
        _, words, expect = parse(path)
        got = run_artifact(words)
        if got != expect:
            print(f"DRIFT {path.name}:\n  recorded: {expect}\n  artifact: {got}")
            bad += 1
        else:
            print(f"ok   {path.name}: {expect}")
    if bad:
        raise SystemExit(f"{bad} example(s) drifted from the artifact")
    print(f"{len(names)} example(s) agree with the artifact")


HEADER = """\
; The example corpus, proved about the model.
;
; Copyright (C) 2026 Kookamara LLC
;
; License: (An MIT/X11-style license)

; GENERATED by ../harness/examples.py --gen-lisp from ../examples/*.mvm.  Do not
; edit: change the example and regenerate.
;
; Each example file holds a program and an expectation RECORDED from the artifact
; by `examples.py --record`, i.e. by running wasm/milawa-verified.wasm in Node.
; This book says the MODEL gives the same answer, and proves it by evaluation.  So
; a passing corpus means:
;
;     the artifact does X            (tested, in Node, untrusted host)
;     the model does X               (proved here, by evaluation)
;
; and the gap between those two sentences -- that they agree for ALL inputs -- is
; L1, which is not proved.  Keeping the two claims separate and both checkable is
; the whole point of the corpus: when L1 lands, these same files become its
; regression suite, and until then they are the honest lower-level stand-in for a
; Milawa events file.

(in-package "MILAWA-WASM")

(include-book "mvm")

; The machine starts running at word 0 with an empty stack and no result, which is
; also what the module's own reset leaves behind.
(defun example-init (code)
  (mvm-make-state 1 0 nil 0 code))

; Examples are proved with a generous fuel: the number of steps actually spent is
; one of the things asserted, so a budget that is merely large enough cannot hide
; a slow program.  (MVM-RUN-MONOTONE says a larger budget changes nothing once the
; machine has stopped, which is why this is safe.)
(defconst *example-fuel* 1000)

"""


def gen_lisp(names):
    parts = [HEADER]
    for path in names:
        _, words, expect = parse(path)
        name = path.stem.replace("-", "_")
        fields = dict(kv.split("=") for kv in expect.split() if "=" in kv)
        status = expect.split()[0]
        conds = ["(equal (mvm-steps (example-init code) *example-fuel*) "
                 f"{fields['steps']})",
                 "(equal (mvm-pc (mvm-run (example-init code) *example-fuel*)) "
                 f"{fields['pc']})"]
        if status == "halted":
            conds.insert(0, "(mvm-haltedp (mvm-run (example-init code) *example-fuel*))")
            conds.insert(1, f"(equal (mvm-result (mvm-run (example-init code) *example-fuel*)) {fields['result']})")
        else:
            conds.insert(0, f"(mvm-abortedp (mvm-run (example-init code) *example-fuel*))")
        body = "\n".join(f"     {c}" for c in conds)
        parts.append(
            f"; {expect}\n"
            f"(assert-event\n"
            f" (let ((code '{lisp(words)}))\n"
            f"   (and\n{body})))\n\n"
        )
    LISP_OUT.write_text("".join(parts))
    print(f"wrote {LISP_OUT.relative_to(PROJECT)} ({len(names)} examples)")


def lisp(words):
    """Pretty-print a word list the way mvm-tests writes programs."""
    out, i = [], 0
    while i < len(words):
        w = words[i]
        if w in (1, 5, 6) and i + 1 < len(words):
            out.append(f"{w} {words[i + 1]}")
            i += 2
        else:
            out.append(str(w))
            i += 1
    return "(" + "  ".join(out) + ")"


def main():
    args = sys.argv[1:]
    if not args or args[0] not in ("--record", "--check", "--gen-lisp"):
        raise SystemExit(__doc__)
    names = sorted(EXAMPLES.glob("*.mvm"))
    if not names:
        raise SystemExit(f"no examples in {EXAMPLES}")
    if args[0] == "--record":
        record(names)
    elif args[0] == "--check":
        check(names)
    else:
        gen_lisp(names)


if __name__ == "__main__":
    main()
