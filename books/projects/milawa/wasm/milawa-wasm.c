/*
 * milawa-wasm: run the Milawa proof checker on WebAssembly.
 *
 * milawa.lsp is cross-compiled to a wasm object (see build-kernel.lisp) and
 * linked into this program; ECL itself is the one built for
 * wasm32-unknown-emscripten.  At startup we suppress the kernel's trailing
 * base-image dump, initialize the compiled kernel, restore a checkpoint
 * directory (the same <level>.<ext>/state.lisp that the native milawa-ecl
 * uses), and replay an .events file.  The state format is shared, so an
 * image written by native ECL works here and vice versa.
 *
 *   node milawa-wasm.js <image-directory> <events-file>
 *
 * ECL is booted with argc = 1 so that it does not try to load our arguments as
 * Lisp files.
 */

#include <ecl/ecl.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

/* Generated by wasm/build.sh: the module init functions of the cross-compiled
 * kernel and driver, whose names contain hashes that change between builds. */
#include "milawa-init.h"

static cl_object
eval_string(const char *s)
{
  return cl_eval(ecl_read_from_cstring(s));
}

/* The real filesystem is mounted at /real (see pre.js), so absolute host
 * paths have to be redirected there. */
static const char *
fs_path(const char *path, char *buffer, size_t cap)
{
  if (path[0] == '/') {
    snprintf(buffer, cap, "/real%s", path);
    return buffer;
  }
  return path;
}

/* The image extension is whatever follows the first dot in the directory
 * name, matching what the native milawa-ecl derives from its images. */
static void
image_extension(const char *image, char *ext, size_t cap)
{
  const char *base = strrchr(image, '/');
  const char *dot;

  base = (base != NULL) ? base + 1 : image;
  dot = strchr(base, '.');
  if (dot != NULL && dot[1] != '\0' && strlen(dot + 1) < cap) {
    strcpy(ext, dot + 1);
  }
}

int
main(int argc, char **argv)
{
  char ext[256] = "wasm";
  char image_buf[4096];
  char events_buf[4096];
  const char *image;
  const char *events;

  cl_boot(1, argv);

  /* milawa.lsp ends with (unless *loading-image* (save-and-exit "base")).
   * Bind the flag before the compiled top-level forms run so that loading the
   * kernel does not try to dump an image. */
  eval_string("(defparameter cl-user::*loading-image* t)");
  /* DEFINE events compile their definitions; the target has no C compiler, so
   * use ECL's bytecodes compiler for them (the proof checker itself is already
   * compiled into this program). */
  eval_string("(ext:install-bytecodes-compiler)");

  ecl_init_module(NULL, MILAWA_INIT);
  ecl_init_module(NULL, DRIVER_INIT);

  if (argc < 3) {
    fprintf(stderr, "usage: node milawa-wasm.js <image-directory> <events-file>\n");
    return 2;
  }

  image = fs_path(argv[1], image_buf, sizeof(image_buf));
  events = fs_path(argv[2], events_buf, sizeof(events_buf));
  image_extension(argv[1], ext, sizeof(ext));

  /* Call the compiled driver (wasm/run.lisp).  It reads the commands itself
   * and handles FINISH by calling DUMP-ECL-IMAGE, rather than going through
   * Milawa's MAIN and SAVE-AND-EXIT: those end with (QUIT), and ECL's QUIT
   * unwinds to the bottom of its toplevel, which does not exist in this
   * embedding -- the unwind crashes under emscripten. */
  cl_funcall(4, ecl_make_symbol("MILAWA-WASM-RUN", "CL-USER"),
             ecl_make_simple_base_string(image, -1),
             ecl_make_simple_base_string(ext, -1),
             ecl_make_simple_base_string(events, -1));

  return 0;
}
